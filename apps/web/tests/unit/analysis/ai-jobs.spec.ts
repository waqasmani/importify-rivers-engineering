import { afterEach, describe, expect, it, vi } from 'vitest'
import { defineComponent, h } from 'vue'
import AiJobsView from '@/views/ai/AiJobsView.vue'
import AiJobView from '@/views/ai/AiJobView.vue'
import ConfirmHost from '@/components/ui/ConfirmHost.vue'
import { mockApi, mountView, settle } from '../helpers'
import { PROJECT_ID } from './fixtures'

afterEach(() => {
  vi.unstubAllGlobals()
  document.body.innerHTML = ''
})

const tool = { key: 'generate_tech_doc', label: 'Generate technical documentation', description: 'Draft documentation', entity_types: ['analysis_project'], apply: 'report', report_kind: 'technical_documentation' }
const row = (id: string, status: string) => ({
  id, tool: 'generate_tech_doc', status, entity_type: 'analysis_project', entity_id: PROJECT_ID, provider_name: 'Local', provider_kind: 'ollama', model: 'llama3.1',
  queued_at: '2026-10-01T10:00:00Z', started_at: null, finished_at: null, applied_at: null, attempts: 0, duration_ms: null, input_tokens: null, output_tokens: null, requested_by: null, error: '', total: 1,
})

describe('AI jobs', () => {
  it('lists jobs with status, tool and mine filters and links to the record', async () => {
    const api = mockApi({
      'GET /ai/jobs': { items: [row('j1', 'succeeded')], total: 1, limit: 50, offset: 0 },
      'GET /ai/tools': { items: [tool], suggested_models: {} },
      'GET /ai/status': { enabled: true, configured: true, default_provider: null },
    })
    const { wrapper, router } = await mountView(AiJobsView, { path: '/ai/jobs' })
    expect(wrapper.text()).toContain('Generate technical documentation')
    expect(wrapper.find('a[href="/ai/jobs/j1"]').exists()).toBe(true)
    expect(wrapper.find(`a[href="/analysis/${PROJECT_ID}"]`).text()).toBe('Analysis project')
    await wrapper.find('#ai-jobs-status').setValue('failed')
    await settle()
    await wrapper.find('#ai-jobs-tool').setValue('generate_tech_doc')
    await settle()
    await wrapper.find('input[type="checkbox"]').setValue(true)
    await settle()
    expect(router.currentRoute.value.query).toMatchObject({ status: 'failed', tool: 'generate_tech_doc', mine: 'true' })
    expect(Object.fromEntries(api.calls.filter((c) => c.path === '/ai/jobs').at(-1)!.query)).toMatchObject({ status: 'failed', tool: 'generate_tech_doc', mine: 'true' })
  })

  it('shows a queued job as AI-generated output in progress and cancels it after confirmation', async () => {
    let status = 'queued'
    const api = mockApi({
      'GET /ai/jobs/j2': () => ({
        job: { ...row('j2', status), input: {}, output: null, output_text: '', grounding: {}, evidence_refs: [], external_data_confirmed: false, max_attempts: 2, locked_by: '', locked_at: null, provider_config_id: null, applied_by: null, apply_result: null },
        tool, ai_generated_notice: 'This output was generated by Local (llama3.1). Verify it against the cited evidence.',
      }),
      'POST /ai/jobs/j2/cancel': () => {
        status = 'cancelled'
        return undefined
      },
    })
    const Host = defineComponent({ props: { id: { type: String, required: true } }, setup: (p) => () => h('div', [h(AiJobView, { id: p.id }), h(ConfirmHost)]) })
    const { wrapper } = await mountView(Host, { path: '/ai/jobs/j2', pattern: '/ai/jobs/:id' })
    expect(wrapper.find('[data-testid="ai-result"]').text()).toContain('AI-generated')
    expect(wrapper.text()).toContain('Waiting for the worker')
    expect(wrapper.find(`a[href="/analysis/${PROJECT_ID}"]`).exists()).toBe(true)
    await wrapper.findAll('button').find((b) => b.text().includes('Cancel job'))!.trigger('click')
    await settle()
    ;(document.querySelector('[data-testid="confirm-ok"]') as HTMLButtonElement).click()
    await settle(5)
    expect(api.calls.some((c) => c.method === 'POST' && c.path === '/ai/jobs/j2/cancel')).toBe(true)
    expect(wrapper.findAll('button').some((b) => b.text().includes('Cancel job'))).toBe(false)
  })
})
