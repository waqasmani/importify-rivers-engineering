package analysis

import (
	"fmt"
	"sort"
	"strings"
	"time"
)

// ReportFinding is a stored finding passed to the report generator.
type ReportFinding struct {
	ID             string
	SourceID       string
	SourceTitle    string
	Category       string
	Title          string
	Detail         string
	Evidence       string
	Locator        string
	Classification string
	Confidence     float64
	Assumptions    string
	Origin         string
	Data           map[string]any
}

// ReportSource describes an analysis source.
type ReportSource struct {
	ID, Title, Kind string
}

// ReportInput is the material a report is built from.
type ReportInput struct {
	ProjectName        string
	Objective          string
	Description        string
	AuthorizationBasis string
	Sources            []ReportSource
	Findings           []ReportFinding
	GeneratedAt        time.Time
}

// ReportKinds lists the deterministic report types.
var ReportKinds = []string{"summary", "technical_documentation", "architecture", "api_inventory", "data_model", "workflow", "reconstruction_plan"}

// Ref is the short citation for a finding, e.g. [F-1a2b3c].
func Ref(id string) string {
	if len(id) >= 6 {
		return "[F-" + id[:6] + "]"
	}
	return "[F-" + id + "]"
}

type reportWriter struct {
	b    strings.Builder
	used map[string]bool
	in   ReportInput
}

func (w *reportWriter) cite(f ReportFinding) string {
	w.used[f.ID] = true
	return Ref(f.ID)
}

func (w *reportWriter) line(format string, a ...any) { fmt.Fprintf(&w.b, format+"\n", a...) }

func (w *reportWriter) byCategory(cats ...string) []ReportFinding {
	var out []ReportFinding
	for _, f := range w.in.Findings {
		for _, c := range cats {
			if f.Category == c {
				out = append(out, f)
				break
			}
		}
	}
	return out
}

func (w *reportWriter) byClass(class string) []ReportFinding {
	var out []ReportFinding
	for _, f := range w.in.Findings {
		if f.Classification == class {
			out = append(out, f)
		}
	}
	return out
}

func mdEscape(s string) string {
	return strings.NewReplacer("|", "\\|", "\n", " ", "\r", " ").Replace(strings.TrimSpace(s))
}

func classLabel(c string) string {
	switch c {
	case Verified:
		return "Verified"
	case Inferred:
		return "Inferred"
	}
	return "Unknown"
}

func (w *reportWriter) header(title string) {
	w.line("# %s", title)
	w.line("")
	w.line("> **Generated by REA's deterministic report generator** on %s from %d findings across %d sources. No AI was used.",
		w.in.GeneratedAt.UTC().Format("2006-01-02 15:04 UTC"), len(w.in.Findings), len(w.in.Sources))
	w.line("> Each statement cites its evidence, for example %s. **Verified** findings were observed directly in a source; **inferred** findings are reasoned conclusions with stated assumptions; **unknown** marks information the sources cannot provide.", Ref("abcdef"))
	w.line("")
	w.line("**Project:** %s  ", mdEscape(w.in.ProjectName))
	if w.in.Objective != "" {
		w.line("**Objective:** %s  ", mdEscape(w.in.Objective))
	}
	w.line("**Authorization basis:** %s", strings.ReplaceAll(w.in.AuthorizationBasis, "_", " "))
	w.line("")
}

func (w *reportWriter) list(fs []ReportFinding, withDetail bool) {
	for _, f := range fs {
		label := ""
		if f.Classification != Verified {
			label = " _(" + strings.ToLower(classLabel(f.Classification)) + fmt.Sprintf(", confidence %.0f%%)_", f.Confidence*100)
		}
		w.line("- %s%s %s", mdEscape(f.Title), label, w.cite(f))
		if withDetail && f.Detail != "" {
			w.line("  - %s", mdEscape(clip(f.Detail, 400)))
		}
		if f.Classification == Inferred && f.Assumptions != "" && withDetail {
			w.line("  - Assumption: %s", mdEscape(clip(f.Assumptions, 300)))
		}
	}
}

func (w *reportWriter) evidenceIndex() {
	if len(w.used) == 0 {
		return
	}
	w.line("")
	w.line("## Evidence index")
	w.line("")
	w.line("| Ref | Finding | Class | Source | Locator |")
	w.line("|---|---|---|---|---|")
	for _, f := range w.in.Findings {
		if !w.used[f.ID] {
			continue
		}
		w.line("| %s | %s | %s | %s | %s |", Ref(f.ID), mdEscape(clip(f.Title, 120)), classLabel(f.Classification),
			mdEscape(clip(firstNonEmpty(f.SourceTitle, "manual"), 60)), mdEscape(clip(f.Locator, 80)))
	}
}

func (w *reportWriter) unknownsSection(title string) {
	unk := w.byClass(Unknown)
	w.line("")
	w.line("## %s", title)
	w.line("")
	if len(unk) == 0 {
		w.line("The analyzers recorded no explicit unknowns. Absence of evidence is not evidence of absence; confirm critical assumptions with the system owner.")
		return
	}
	seen := map[string]bool{}
	for _, f := range unk {
		if seen[f.Title] {
			continue
		}
		seen[f.Title] = true
		w.line("- **%s** %s — %s", mdEscape(f.Title), w.cite(f), mdEscape(clip(f.Detail, 300)))
	}
}

// GenerateReport builds a Markdown report of the given kind.
func GenerateReport(kind string, in ReportInput) (string, string, []string, error) {
	if in.GeneratedAt.IsZero() {
		in.GeneratedAt = time.Now()
	}
	sort.SliceStable(in.Findings, func(i, j int) bool {
		if in.Findings[i].Category != in.Findings[j].Category {
			return in.Findings[i].Category < in.Findings[j].Category
		}
		return in.Findings[i].Confidence > in.Findings[j].Confidence
	})
	w := &reportWriter{used: map[string]bool{}, in: in}
	var title string
	switch kind {
	case "summary":
		title = "Analysis summary: " + in.ProjectName
		w.header(title)
		w.summary()
	case "technical_documentation":
		title = "Technical documentation: " + in.ProjectName
		w.header(title)
		w.technical()
	case "architecture":
		title = "Architecture overview: " + in.ProjectName
		w.header(title)
		w.architecture()
	case "api_inventory":
		title = "API inventory: " + in.ProjectName
		w.header(title)
		w.apiInventory()
	case "data_model":
		title = "Data model: " + in.ProjectName
		w.header(title)
		w.dataModel()
	case "workflow":
		title = "Workflows: " + in.ProjectName
		w.header(title)
		w.workflows()
	case "reconstruction_plan":
		title = "Reconstruction plan: " + in.ProjectName
		w.header(title)
		w.reconstruction()
	default:
		return "", "", nil, fmt.Errorf("unknown report kind %q", kind)
	}
	w.evidenceIndex()
	used := make([]string, 0, len(w.used))
	for id := range w.used {
		used = append(used, id)
	}
	sort.Strings(used)
	return title, w.b.String(), used, nil
}

func (w *reportWriter) summary() {
	counts := map[string]map[string]int{}
	for _, f := range w.in.Findings {
		if counts[f.Category] == nil {
			counts[f.Category] = map[string]int{}
		}
		counts[f.Category][f.Classification]++
	}
	w.line("## Sources")
	w.line("")
	for _, s := range w.in.Sources {
		w.line("- %s (%s)", mdEscape(s.Title), strings.ReplaceAll(s.Kind, "_", " "))
	}
	w.line("")
	w.line("## Findings by category")
	w.line("")
	w.line("| Category | Verified | Inferred | Unknown |")
	w.line("|---|---|---|---|")
	for _, c := range sortedKeys(counts) {
		w.line("| %s | %d | %d | %d |", strings.ReplaceAll(c, "_", " "), counts[c][Verified], counts[c][Inferred], counts[c][Unknown])
	}
	w.line("")
	w.line("## Key verified evidence")
	w.line("")
	ver := w.byClass(Verified)
	w.list(ver[:min(25, len(ver))], false)
	w.line("")
	w.line("## Inferences")
	w.line("")
	inf := w.byClass(Inferred)
	if len(inf) == 0 {
		w.line("None recorded.")
	}
	w.list(inf[:min(25, len(inf))], true)
	w.unknownsSection("Unknowns")
}

func (w *reportWriter) technical() {
	sections := []struct {
		title string
		cats  []string
	}{
		{"Technologies", []string{"technology", "language"}},
		{"Structure and modules", []string{"structure", "architecture", "entry_point", "navigation"}},
		{"Dependencies", []string{"dependency"}},
		{"Routes and endpoints", []string{"route", "endpoint", "api"}},
		{"Authentication", []string{"auth", "authentication"}},
		{"Data models and schemas", []string{"data_model", "schema", "entity"}},
		{"Forms and inputs", []string{"form"}},
		{"Configuration", []string{"configuration"}},
		{"Infrastructure and build", []string{"infrastructure", "build"}},
		{"Integrations", []string{"integration"}},
		{"Requirements", []string{"requirement"}},
		{"Security notes", []string{"security"}},
	}
	for _, s := range sections {
		fs := w.byCategory(s.cats...)
		var known []ReportFinding
		for _, f := range fs {
			if f.Classification != Unknown {
				known = append(known, f)
			}
		}
		if len(known) == 0 {
			continue
		}
		w.line("## %s", s.title)
		w.line("")
		w.list(known[:min(60, len(known))], true)
		w.line("")
	}
	w.unknownsSection("Gaps and unknowns")
}

func (w *reportWriter) architecture() {
	w.line("## Components")
	w.line("")
	comps := w.byCategory("technology", "component", "entry_point", "infrastructure")
	if len(comps) == 0 {
		w.line("No components were identified in the evidence.")
	}
	w.list(comps, true)
	w.line("")
	graphs := w.byCategory("architecture")
	if len(graphs) > 0 {
		w.line("## Module relationships")
		w.line("")
		w.line("```mermaid")
		w.line("graph LR")
		for _, g := range graphs {
			w.used[g.ID] = true
			if gm, ok := g.Data["graph"].(map[string]any); ok {
				for _, from := range sortedKeys(gm) {
					for _, to := range anySlice(gm[from]) {
						w.line("  %s[\"%s\"] --> %s[\"%s\"]", mermaidID(from), MermaidLabel(from), mermaidID(str(to)), MermaidLabel(str(to)))
					}
				}
			}
		}
		w.line("```")
		w.line("")
		w.line("Derived from static imports %s.", Ref(graphs[0].ID))
		w.line("")
	}
	integ := w.byCategory("integration", "dependency")
	if len(integ) > 0 {
		w.line("## External dependencies and integrations")
		w.line("")
		w.list(integ, false)
	}
	w.unknownsSection("What the evidence cannot show")
}

func (w *reportWriter) apiInventory() {
	eps := w.byCategory("endpoint", "route")
	w.line("## Endpoints")
	w.line("")
	if len(eps) == 0 {
		w.line("No endpoints were found. Import an OpenAPI description, recorded API examples or an authorized codebase.")
	} else {
		w.line("| Method | Path | Summary | Auth | Evidence |")
		w.line("|---|---|---|---|---|")
		for _, f := range eps {
			if f.Classification == Unknown || f.Data["method"] == nil {
				continue
			}
			auth := ""
			if s, ok := f.Data["secured"].(bool); ok {
				auth = map[bool]string{true: "required", false: "none declared"}[s]
			}
			w.line("| %s | `%s` | %s | %s | %s |", str(f.Data["method"]), mdEscape(str(f.Data["path"])), mdEscape(clip(firstNonEmpty(str(f.Data["summary"]), f.Detail), 120)), auth, w.cite(f))
		}
	}
	if schemes := w.byCategory("auth"); len(schemes) > 0 {
		w.line("")
		w.line("## Authentication")
		w.line("")
		w.list(schemes, true)
	}
	if schemas := w.byCategory("schema"); len(schemas) > 0 {
		w.line("")
		w.line("## Schemas")
		w.line("")
		for _, s := range schemas {
			w.line("### %s %s", mdEscape(strings.TrimPrefix(s.Title, "Schema: ")), w.cite(s))
			w.line("")
			w.line("```")
			w.line("%s", s.Evidence)
			w.line("```")
		}
	}
	w.line("")
	w.line("## Integration notes")
	w.line("")
	w.line("- Treat undocumented behaviour (rate limits, pagination, error formats) as unknown until confirmed with the API owner.")
	w.line("- Use only credentials issued to you for authorized integration; REA never stores captured credentials.")
	w.unknownsSection("Unknowns")
}

func (w *reportWriter) dataModel() {
	type entity struct {
		name   string
		fields []map[string]any
		refs   []ReportFinding
	}
	ents := map[string]*entity{}
	add := func(name string, f ReportFinding, fields []map[string]any) {
		if name == "" {
			return
		}
		e := ents[name]
		if e == nil {
			e = &entity{name: name}
			ents[name] = e
		}
		e.refs = append(e.refs, f)
		if len(e.fields) == 0 {
			e.fields = fields
		}
	}
	for _, f := range w.byCategory("data_model", "schema", "entity") {
		var fields []map[string]any
		for _, x := range anySlice(f.Data["fields"]) {
			if m, ok := x.(map[string]any); ok {
				fields = append(fields, m)
			}
		}
		if fs, ok := f.Data["fields"].([]map[string]any); ok {
			fields = fs
		}
		add(firstNonEmpty(str(f.Data["name"]), strings.TrimPrefix(strings.TrimPrefix(strings.TrimPrefix(f.Title, "Data model: "), "Schema: "), "Entity: ")), f, fields)
	}
	products := w.byCategory("product")
	if len(products) > 0 {
		fields := []map[string]any{}
		seen := map[string]bool{}
		for _, p := range products {
			for k := range p.Data {
				if !seen[k] && k != "extracted" {
					seen[k] = true
					fields = append(fields, map[string]any{"name": k, "type": "observed"})
				}
			}
		}
		add("Product", products[0], fields)
	}
	if len(ents) == 0 {
		w.line("No entities were identified. Add a codebase, API description or workflow with data items.")
		w.unknownsSection("Unknowns")
		return
	}
	w.line("## Entities")
	w.line("")
	for _, name := range sortedKeys(ents) {
		e := ents[name]
		var cites []string
		for _, r := range e.refs {
			cites = append(cites, w.cite(r))
		}
		w.line("### %s %s", mdEscape(name), strings.Join(uniq(cites), " "))
		w.line("")
		if len(e.fields) == 0 {
			w.line("Fields are not visible in the evidence.")
		} else {
			w.line("| Field | Type | Required |")
			w.line("|---|---|---|")
			for _, f := range e.fields {
				w.line("| %s | %s | %v |", mdEscape(str(f["name"])), mdEscape(str(f["type"])), f["required"] == true)
			}
		}
		w.line("")
	}
	w.line("## Entity diagram")
	w.line("")
	w.line("```mermaid")
	w.line("erDiagram")
	names := sortedKeys(ents)
	for _, name := range names {
		e := ents[name]
		w.line("  %s {", mermaidID(name))
		for _, f := range e.fields[:min(20, len(e.fields))] {
			typ := mermaidID(strings.Fields(firstNonEmpty(str(f["type"]), "field") + " x")[0])
			w.line("    %s %s", typ, mermaidID(str(f["name"])))
		}
		w.line("  }")
	}
	for _, name := range names {
		for _, f := range ents[name].fields {
			t := str(f["type"])
			for _, other := range names {
				if other != name && (t == other || t == "array of "+other) {
					card := "||--o|"
					if strings.HasPrefix(t, "array") {
						card = "||--o{"
					}
					w.line("  %s %s %s : %s", mermaidID(name), card, mermaidID(other), mermaidID(str(f["name"])))
				}
			}
		}
	}
	w.line("```")
	w.line("")
	w.line("Relationships are drawn only where a field's type names another entity; foreign keys hidden in code are not inferred.")
	w.unknownsSection("Unknowns")
}

func (w *reportWriter) workflows() {
	diags := w.byCategory("diagram")
	steps := w.byCategory("workflow_step")
	if len(steps) == 0 {
		w.line("No workflows were recorded. Add a workflow source with observed steps.")
		return
	}
	bySource := map[string][]ReportFinding{}
	for _, s := range steps {
		bySource[s.SourceTitle] = append(bySource[s.SourceTitle], s)
	}
	for _, src := range sortedKeys(bySource) {
		w.line("## %s", mdEscape(firstNonEmpty(src, "Workflow")))
		w.line("")
		w.line("| # | Step | Evidence |")
		w.line("|---|---|---|")
		for i, s := range bySource[src] {
			w.line("| %d | %s | %s |", i+1, mdEscape(strings.TrimPrefix(s.Title, fmt.Sprintf("Step %d: ", i+1))), w.cite(s))
		}
		w.line("")
		for _, d := range diags {
			if d.SourceTitle == src {
				w.line("```mermaid")
				w.line("%s", strings.TrimSpace(str(d.Data["mermaid"])))
				w.line("```")
				w.line("")
				if seq := str(d.Data["sequence"]); seq != "" {
					w.line("```mermaid")
					w.line("%s", strings.TrimSpace(seq))
					w.line("```")
					w.line("")
				}
				w.used[d.ID] = true
			}
		}
	}
	if reqs := w.byCategory("requirement"); len(reqs) > 0 {
		w.line("## Derived requirements")
		w.line("")
		w.list(reqs, false)
	}
	if ents := w.byCategory("entity", "actor"); len(ents) > 0 {
		w.line("")
		w.line("## Actors and entities")
		w.line("")
		w.list(ents, false)
	}
}

func (w *reportWriter) reconstruction() {
	w.line("This plan describes how to build an **original** system with similar documented functionality. It must not copy proprietary source code, assets, text or trade dress from the analyzed system, and it relies only on the authorized evidence cited below.")
	w.line("")
	w.line("## 1. Evidence base")
	w.line("")
	kinds := map[string]int{}
	for _, s := range w.in.Sources {
		kinds[s.Kind]++
	}
	for _, k := range sortedKeys(kinds) {
		w.line("- %d %s source(s)", kinds[k], strings.ReplaceAll(k, "_", " "))
	}
	ver, inf, unk := len(w.byClass(Verified)), len(w.byClass(Inferred)), len(w.byClass(Unknown))
	w.line("- %d verified, %d inferred and %d unknown findings", ver, inf, unk)
	w.line("")

	w.line("## 2. Functional scope")
	w.line("")
	feats := w.byCategory("navigation", "form", "workflow_step", "requirement", "endpoint", "route", "product", "authentication")
	if len(feats) == 0 {
		w.line("The evidence does not describe user-facing functionality yet. Capture key pages, record workflows or import API descriptions first.")
	}
	w.list(feats[:min(60, len(feats))], false)
	w.line("")

	w.line("## 3. Proposed components")
	w.line("")
	tech := w.byCategory("technology", "language")
	hasFrontend, hasAPI, hasData, hasAuth := false, false, false, false
	for _, f := range w.in.Findings {
		switch f.Category {
		case "navigation", "form", "structure":
			hasFrontend = true
		case "endpoint", "route", "api":
			hasAPI = true
		case "data_model", "schema", "entity", "product":
			hasData = true
		case "authentication", "auth":
			hasAuth = true
		}
	}
	w.line("| Component | Why it is needed | Evidence |")
	w.line("|---|---|---|")
	firstCite := func(cats ...string) string {
		fs := w.byCategory(cats...)
		if len(fs) == 0 {
			return "_none — assumption_"
		}
		return w.cite(fs[0])
	}
	if hasFrontend {
		w.line("| Web user interface | Pages, navigation and forms were observed | %s |", firstCite("navigation", "form", "structure"))
	}
	if hasAPI || hasFrontend {
		w.line("| Application API | Serves the interface and integrations | %s |", firstCite("endpoint", "route", "form"))
	}
	if hasData {
		w.line("| Relational database | Entities and attributes were identified | %s |", firstCite("data_model", "schema", "entity", "product"))
	}
	if hasAuth {
		w.line("| Authentication and accounts | Sign-in or security schemes were observed | %s |", firstCite("authentication", "auth"))
	}
	if integ := w.byCategory("integration"); len(integ) > 0 {
		w.line("| Third-party integrations | External services are referenced | %s |", w.cite(integ[0]))
	}
	w.line("")
	if len(tech) > 0 {
		w.line("Technologies observed in the source system are listed for context only; choose the stack for the new system on its own merits:")
		w.line("")
		w.list(tech[:min(20, len(tech))], false)
		w.line("")
	}

	w.line("## 4. Data model")
	w.line("")
	ents := w.byCategory("data_model", "schema", "entity")
	if len(ents) == 0 {
		w.line("No entities are evidenced. **Missing information:** confirm the core records (for example customers, orders, products) with stakeholders.")
	}
	w.list(ents[:min(40, len(ents))], false)
	w.line("")

	w.line("## 5. API surface")
	w.line("")
	eps := w.byCategory("endpoint", "route")
	if len(eps) == 0 {
		w.line("No API evidence. Design the API from the functional scope and data model.")
	}
	w.list(eps[:min(60, len(eps))], false)
	w.line("")

	w.line("## 6. Implementation phases")
	w.line("")
	phase := 1
	task := func(title string, items ...string) {
		w.line("### Phase %d — %s", phase, title)
		w.line("")
		for _, it := range items {
			w.line("- [ ] %s", it)
		}
		w.line("")
		phase++
	}
	task("Foundations", "Set up the repository, CI, environments and secret management.", "Define the data model and migrations from section 4.",
		"Implement authentication and roles"+map[bool]string{true: " (evidenced)", false: " (assumption: confirm requirements)"}[hasAuth]+".")
	if hasAPI || hasData {
		task("Core API", "Implement CRUD for each entity with validation and authorization.", "Implement the endpoints in section 5, writing original code against the documented contract.",
			"Write contract tests from the API inventory.")
	}
	if hasFrontend {
		task("User interface", "Build the navigation structure and pages identified in the evidence.", "Implement forms with validation matching observed required fields.",
			"Design an original visual identity; do not reuse the analyzed system's assets.")
	}
	if len(w.byCategory("workflow_step")) > 0 {
		task("Workflows", "Implement each recorded workflow end to end.", "Turn derived requirements into acceptance tests.")
	}
	if len(w.byCategory("integration")) > 0 {
		task("Integrations", "Select providers for each integration point and obtain your own credentials and agreements.")
	}
	task("Hardening and launch", "Load-test, security review, backups and monitoring.", "Validate every unknown in section 7 before launch.")

	w.unknownsSection("7. Missing information and unknowns")
	w.line("")
	w.line("## 8. Assumptions to confirm")
	w.line("")
	inferred := w.byClass(Inferred)
	if len(inferred) == 0 {
		w.line("No inferred findings.")
	}
	for _, f := range inferred[:min(30, len(inferred))] {
		w.line("- %s %s — %s", mdEscape(f.Title), w.cite(f), mdEscape(clip(firstNonEmpty(f.Assumptions, f.Detail), 250)))
	}
}
